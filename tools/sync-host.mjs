import {readFile, writeFile, mkdir, readdir, lstat} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {englishDeclarations, englishProtocol} from './sdk-english.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const sourceIndex = args.indexOf('--source');
const source = path.resolve(sourceIndex < 0 ? path.join(root, '../Widget Workshop') : args[sourceIndex + 1]);
const check = args.includes('--check');
const hash = value => createHash('sha256').update(value).digest('hex');
const pairs = new Map();
for (const name of ['component', 'configuration', 'host-api', 'layout', 'saves', 'cache', 'reminders', 'collaboration', 'desktop-extensions', 'system-integration']) {
  pairs.set(`docs/contracts/${name}.md`, `docs/reference/contracts/${name}.md`);
}
for (const name of ['development', 'runtime', 'audio', 'github', 'edge-garden', 'stardust', 'file-tool', 'media', 'workshop']) {
  pairs.set(`docs/modules/${name}.md`, `docs/reference/modules/${name}.md`);
}
pairs.set('docs/CONTEXT.md', 'docs/reference/glossary.md');
for (const name of ['widget-host.d.ts', 'protocol.json']) pairs.set(`sdk/${name}`, `docs/public/sdk/${name}`);
const sampleNames = ['transparent-pet', 'edge-garden', 'stardust', 'worker-canvas', 'file-tool'];
async function walk(relative) {
  const absolute = path.join(source, relative);
  if ((await lstat(absolute)).isSymbolicLink()) throw new Error(`Refuse symlink: ${relative}`);
  const items = await readdir(absolute, {withFileTypes: true});
  for (const item of items.sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const next = `${relative}/${item.name}`;
    if (item.isSymbolicLink()) throw new Error(`Refuse symlink: ${next}`);
    if (item.isDirectory()) await walk(next);
    else if (item.isFile()) pairs.set(next, next);
  }
}
for (const name of sampleNames) await walk(`examples/${name}`);

const records = [];
const changes = [];
async function output(destination, value) {
  const full = path.join(root, destination);
  let current;
  try { current = await readFile(full); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const buffer = Buffer.isBuffer(value) ? value : Buffer.from(value);
  if (current?.equals(buffer)) return;
  changes.push(destination);
  if (!check) {
    await mkdir(path.dirname(full), {recursive: true});
    await writeFile(full, buffer);
  }
}
for (const [from, to] of pairs) {
  const input = await readFile(path.join(source, from));
  let value = input;
  if (/\.(?:js|ts|json|html|css|txt)$/i.test(from)) {
    value = input.toString('utf8').replace(/\r\n/g, '\n');
  }
  if (from.endsWith('.md')) {
    // 只调整站内引用和来源提示，不在生成副本中另行改写协议。
    const markdown = input.toString('utf8').replace(/\r\n/g, '\n');
    const linked = markdown.replace(/\[([^\]]+)\]\(([^)]+)\)/g, (match, label, target) => {
      if (/^(?:https?:|#|mailto:)/.test(target)) return match;
      const [pathname, anchor] = target.split('#');
      const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(from), pathname));
      const mapped = pairs.get(resolved);
      if (!mapped) return `${label}（宿主文档：\`${target}\`）`;
      const relative = path.posix.relative(path.posix.dirname(to), mapped);
      return `[${label}](${relative}${anchor ? `#${anchor}` : ''})`;
    });
    value = `<!-- Generated by tools/sync-host.mjs; source: ${from}. Do not edit. -->\n\n${linked}`;
  }
  await output(to, value);
  records.push({source: from, destination: to, sourceSha256: hash(input), sha256: hash(value)});
}
const declarationSource = await readFile(path.join(source, 'sdk/widget-host.d.ts'));
const englishTypes = englishDeclarations(declarationSource.toString('utf8'));
await output('docs/public/sdk/widget-host.en.d.ts', englishTypes);
records.push({source: 'sdk/widget-host.d.ts', destination: 'docs/public/sdk/widget-host.en.d.ts', sourceSha256: hash(declarationSource), sha256: hash(englishTypes)});
const protocolSource = await readFile(path.join(source, 'sdk/protocol.json'));
const englishMachineProtocol = englishProtocol(protocolSource.toString('utf8'));
await output('docs/public/sdk/protocol.en.json', englishMachineProtocol);
records.push({source: 'sdk/protocol.json', destination: 'docs/public/sdk/protocol.en.json', sourceSha256: hash(protocolSource), sha256: hash(englishMachineProtocol)});
records.sort((a, b) => a.source.localeCompare(b.source, 'en'));
await output('host-snapshot.json', JSON.stringify({sdkVersion: JSON.parse(await readFile(path.join(source, 'sdk/protocol.json'), 'utf8')).sdkVersion, files: records}, null, 2) + '\n');
if (check && changes.length) throw new Error(`Host snapshot is stale:\n${changes.join('\n')}`);
console.log(`${check ? 'Verified' : 'Synchronized'} ${pairs.size} host files (${changes.length} changed).`);
